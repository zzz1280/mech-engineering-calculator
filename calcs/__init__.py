"""机械工程计算器 —— 纯函数公式库（阶段 1）

设计原则（写给自己和读者看的）：
1. 本包**不含任何 Web 代码**，是纯 Python 函数：输入 dict / 显式参数 → 输出 dict。
   这样才能脱离 Flask 单独被 pytest 测试，也方便以后被命令行、Excel 复用。
2. **单位只在最外层（Web 表单 / 打印）换算，内部一律 SI**。
   工程计算 90% 的 bug 来自单位混乱，统一内部单位制是最省事的防御。
3. 每个模块的 docstring 都写明「公式出处」，抄错公式是本项目最大风险，
   所以出处必须能被你（朱锦琰）拿着教材逐行核对。

单位总表（内部一律 SI）：
    长度 / 坐标      m
    力 / 载荷        N
    均布载荷         N/m
    力矩 / 弯矩      N·m
    弹性模量 E       Pa
    截面惯性矩 I     m^4
    应力             Pa
    转速             r/min（寿命公式直接要它，故不换成 rad/s）
    公差             μm（唯一例外：公差行业惯例就是 μm，见 fits.py 说明）
"""

